  function getLang() {
    var saved = null;
    try { saved = localStorage.getItem(STORE_KEY); } catch (e) { saved = null; }
    return SUPPORTED.indexOf(saved) !== -1 ? saved : DEFAULT_LANG;
  }

  function lookup(key, lang) {
    var parts = key.split('.');
    var ns = parts[0], name = parts[1];
    var bucket = T[ns];
    if (!bucket) return null;
    var table = bucket[lang] || bucket[DEFAULT_LANG];
    return table ? table[name] : null;
  }

  function applyLang(lang) {
    document.documentElement.lang = lang;

    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), function (el) {
      var value = lookup(el.getAttribute('data-i18n'), lang);
      if (value == null) return;
      el.textContent = value;
      if (el.hasAttribute('data-idle')) el.setAttribute('data-idle', value);
    });

    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-html]'), function (el) {
      var value = lookup(el.getAttribute('data-i18n-html'), lang);
      if (value != null) el.innerHTML = value;
    });

    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-attrs]'), function (el) {
      var spec = el.getAttribute('data-i18n-attrs');
      spec.split(';').forEach(function (pair) {
        pair = pair.trim();
        if (!pair) return;
        var sep = pair.indexOf(':');
        if (sep === -1) return;
        var attrName = pair.slice(0, sep).trim();
        var key = pair.slice(sep + 1).trim();
        var value = lookup(key, lang);
        if (value != null) el.setAttribute(attrName, value);
      });
    });

    // A plant left pressed from before the switch shows its note in the old
    // language until refreshed — data-note above is already translated.
    Array.prototype.forEach.call(document.querySelectorAll('.bed'), function (bed) {
      var note = bed.querySelector('.garden-note');
      var pressed = bed.querySelector('.plant[aria-pressed="true"]');
      if (note && pressed) note.textContent = pressed.dataset.note || note.getAttribute('data-idle') || note.textContent;
    });
  }

  var langBar = document.querySelector('.langs');

  function setLang(lang) {
    if (SUPPORTED.indexOf(lang) === -1) lang = DEFAULT_LANG;
    applyLang(lang);
    if (langBar) {
      Array.prototype.forEach.call(langBar.querySelectorAll('.langs__opt'), function (opt) {
        opt.setAttribute('aria-pressed', opt.dataset.lang === lang ? 'true' : 'false');
      });
    }
    try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* private mode */ }
  }

  setLang(getLang());

  if (langBar) {
    langBar.addEventListener('click', function (e) {
      var opt = e.target.closest('.langs__opt');
      if (opt) setLang(opt.dataset.lang);
    });
  }
